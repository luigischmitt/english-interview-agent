export type Locale = "pt-BR" | "en";

export const localeStorageKey = "eia:locale-preference";
const localeChangeEvent = "eia:locale-preference-change";
let memoryLocale: Locale | null = null;
let activeLocale: Locale = "pt-BR";

function getStorage(): Storage | null {
  try { return window.localStorage; } catch { return null; }
}

function readLocale(): Locale {
  if (memoryLocale) return memoryLocale;
  try { return getStorage()?.getItem(localeStorageKey) === "en" ? "en" : "pt-BR"; } catch { return "pt-BR"; }
}

function subscribe(onChange: () => void) {
  window.addEventListener(localeChangeEvent, onChange);
  window.addEventListener("storage", onChange);
  return () => {
    window.removeEventListener(localeChangeEvent, onChange);
    window.removeEventListener("storage", onChange);
  };
}

